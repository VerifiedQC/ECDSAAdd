"""Extract the observed Tmin metadata borrows, without simulating an allocator."""
import gzip
import json
from pathlib import Path
import sys

root = Path(__file__).resolve().parents[2]
def load(name):
    data = json.loads(gzip.decompress((root / f'data/paper935/hmr-source-{name}.json.gz').read_bytes()))
    assert data['source_commit'] == '64b5a13aa249f1360846657392e6c66817b26d0f'
    return data['stages']
allocations, controls, resizes = map(load, ('allocations', 'control', 'resize'))
lines = ['import ECDSAAdd.Arithmetic.Paper935.HmrArmRelease', '',
         'namespace ECDSAAdd.Arithmetic.Paper935', '',
         '/- Generated by generate_arm_instances.py from the two observed arm boundaries.',
         'These allocation checks do not certify the full walk or inverse cleanup. -/', '']
for phase in ('s2-walkA', 's6-walkC'):
    control = next(s for s in controls if s['phase'] == phase and not s['early'])
    t = control['step']
    assert t == control['tmin'] == 498
    a = next(s for s in allocations if (s['phase'], s['step'], s['stage']) == (phase, t, 'add'))
    r = next(s for s in resizes if (s['phase'], s['step'], s['stage']) == (phase, t, 'add'))
    wires = control['timestamp'] + [control['frozen']]
    assert len(wires) == 7
    assert a['events'][:7] == [dict(kind='take', wire=q, via='builder') for q in wires]
    live = {q for lo, hi in a['live_before'] for q in range(lo, hi)}
    assert not live.intersection(wires)
    assert live | set(wires) == {q for lo, hi in r['resizes'][0]['live_before'] for q in range(lo, hi)}
    name = phase[:2] + 'ArmBoundary'
    intervals = ' ∨ '.join(f'({lo} ≤ q ∧ q < {hi})' for lo, hi in a['live_before'])
    lines += [f'def {name}Arena : Arena :=',
              f'  ⟨arenaWires.filter (fun q => {intervals}),Finset.filter_subset _ _⟩', '',
              f'def {name}Metadata : HmrFreezeMetadata := ⟨{control["timestamp"]},{control["frozen"]}⟩', '',
              f'theorem {name}_checked :',
              f'    (compileHmrArmLog {name}Arena 6 {name}Metadata).map (fun B => B.live.card) =',
              f'      some {len(live)+7} := by', '  decide +kernel', '',
              f'theorem {name}_input_card : {name}Arena.live.card={len(live)} := by',
              '  decide +kernel', '']
lines += ['end ECDSAAdd.Arithmetic.Paper935', '']
path = root / 'ECDSAAdd/Arithmetic/Paper935/HmrSourceArmInitial.lean'
text = '\n'.join(lines)
if '--check' in sys.argv:
    assert path.read_text() == text, 'Arm boundary fixtures differ from source data'
else:
    path.write_text(text)
